"""Render a discovery universe separately from evidenced corporate initiatives."""
import json

FORMS = {
    "independent_organization": "独立机构",
    "corporate_spinout": "大厂拆分机构",
    "corporate_subsidiary": "子公司",
    "internal_team": "内部团队／创业单元",
    "research_lab": "研究实验室",
    "product_project": "产品／研究项目",
    "unresolved": "组织形态待核实",
}
RELATIONSHIPS = {"confirmed": "有明确证据", "reported": "据报道", "unresolved": "待核实"}
GROUPS = {"internet_platform": "互联网与数字平台", "cloud_ict_adjacent": "云、ICT与终端集团", "software_and_ai": "软件与成熟技术供应商", "hardware_and_semiconductors": "硬件、芯片与基础设施", "industry_incumbents": "跨行业已有玩家"}
ACCESS = {"content_read": "已读取", "limited": "访问受限", "search_only": "仅检索线索"}


def md(value):
    return str(value).replace("|", "\\|").replace("\n", "<br>")


def context_markdown(record):
    context = record.get("organizational_context")
    if not context:
        return ""
    return ("## 组织形态与母平台\n\n**形态：** " + FORMS[context["form"]] +
            "；**关系证据：** " + RELATIONSHIPS[context["relationship_status"]] +
            "；母平台 ID：" + ", ".join(context["parent_platform_ids"]) + "。\n\n" +
            context["summary"] + "\n\n关系核查日期：" + context["checked_at"] +
            "；依据：" + ", ".join(context["source_ids"]) +
            "。内部单元不自动视为独立法人；拆分不等于母公司退出或不再控股。\n\n")


def render(root):
    registry = json.loads((root / "data/platforms.json").read_text())
    platforms = {p["id"]: p for p in registry["platforms"]}
    banner = "<!-- Generated by tools/build.py from canonical JSON. Do not edit by hand. -->\n\n"
    page = banner + "# 中国已有玩家与母平台发现底表\n\n[项目首页](../../README.md) · [机器清单](../platforms.json) · [已有玩家方法](../../skills/find-incumbents/SKILL.md) · [项目与拆分机构](corporate-ventures.md)\n\n"
    page += registry["scope_note"] + "\n\n"
    page += "这是查找已有业务、具体团队及新孵化项目的起点，不是正式目标、已发现岗位或股权关系清单。公司规模不自动表示主题能力领先；访问官网不等于项目核验，不将全部机构统称为 hyperscaler。硬件与软件标签可交叉，主题证据缺失表示尚未附入本表，不等于没有相关业务。\n\n"
    for group, title in GROUPS.items():
        entries = [p for p in platforms.values() if p["group"] == group]
        page += "## %s · %d 个入口\n\n| 机构／平台 | ID | 业务标签 | 官方入口 | 本次访问 | 口径说明 |\n| --- | --- | --- | --- | --- | --- |\n" % (title, len(entries))
        for p in entries:
            page += "| %s | `%s` | %s | [官方入口](%s) | %s · %s | %s |\n" % tuple(map(md, [p["name"], p["id"], ", ".join(p.get("sectors", [])), p["official_url"], ACCESS[p["access"]], p["checked_at"], p["notes"]]))
        page += "\n"
    page += "## 已附的主题活动证据\n\n以下只展示明确附入的材料；与正式机构档案、市场地位和当前岗位分别核验。历史公告保留原公开日期。\n\n| 机构 | 主题／角色 | 来源 | 支持范围 | 公开日期 | 核查日期 |\n| --- | --- | --- | --- | --- | --- |\n"
    for p in platforms.values():
        for e in p.get("topic_evidence", []):
            page += "| %s | %s / %s | [%s](%s) | %s | %s | %s |\n" % tuple(map(md, [p["name"], e["topic"], e["role"], e["title"], e["url"], e["supports"], e["published_date"] or "未标明", e["checked_at"]]))
    initiatives = []
    for path in sorted((root / "data/companies").glob("*.json")):
        record = json.loads(path.read_text())
        if record.get("organizational_context", {}).get("parent_platform_ids"):
            initiatives.append(record)
    venture = banner + "# 大厂项目、实验室与拆分机构\n\n[第一波名单](first-wave.md) · [平台排查清单](platforms.md) · [识别 SOP](../../skills/find-incumbents/references/corporate-ventures.md)\n\n"
    venture += "这里按具体研究或业务单元建档；母平台本身是否属于已有玩家，与该单元是否属于第一波候选分别判断。组织形态和母平台关系未标注的旧记录，不默认视为独立机构。\n\n| 单元／机构 | 组织形态 | 母平台 | 关系证据 | 寻源状态 |\n| --- | --- | --- | --- | --- |\n"
    for r in initiatives:
        c = r["organizational_context"]
        parents = "、".join(platforms[p]["name"] for p in c["parent_platform_ids"])
        venture += "| [%s](companies/%s.md) | %s | %s | %s | %s |\n" % tuple(map(md, [r["name"], r["id"], FORMS[c["form"]], parents, RELATIONSHIPS[c["relationship_status"]], r["targeting"]["wave"]]))
    return {"data/views/platforms.md": page.rstrip() + "\n", "data/views/corporate-ventures.md": venture.rstrip() + "\n"}
