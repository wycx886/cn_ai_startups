"""Render first-wave organization lists from editorial labels stored in canonical JSON."""
import csv
import io
import json
from collections import Counter

WAVES = {"first": "第一波候选", "watchlist": "观察候选", "later": "已有玩家／后续"}
TYPES = {"operating_organization": "经营型机构", "investment_firm": "投资机构"}
FUNDING = {"confirmed_disclosure": "已核验披露", "partial": "部分核验／口径有限", "not_found": "未找到可靠披露", "not_applicable": "内部单元／独立股权融资不适用"}


def md(value):
    return str(value).replace("|", "\\|").replace("\n", "<br>")


def build_index(root, records=None):
    """One lookup index preserves metadata formerly spread over three indexes."""
    from investors import cohort, GROUPS, ROLES

    if records is None:
        from organizations import select
        records = select(root)
    records = sorted(records, key=lambda item: (item[1]["organization_type"], item[1]["id"]))
    taxonomy = json.loads((root / "data/taxonomy.json").read_text())
    categories = {c["id"]: c["name"] for c in taxonomy["categories"]}
    companies = [r for folder, r in records if r["organization_type"] == "operating_organization"]
    investors = [r for folder, r in records if r["organization_type"] == "investment_firm"]
    waves = Counter(r["targeting"]["wave"] for _, r in records)
    entries = []
    for folder, record in records:
        entry = {key: record[key] for key in (
            "id", "name", "aliases", "organization_type", "focus", "checked_at", "targeting")}
        entry.update(json_path=f"data/{folder}/{record['id']}.json",
                     markdown_path=f"data/views/{folder}/{record['id']}.md")
        if record["organization_type"] == "operating_organization":
            entry.update(category_id=record["category_id"],
                         category_name=categories[record["category_id"]],
                         investment_status=record["investment"]["verification_status"])
            if "organizational_context" in record:
                entry["organizational_context"] = record["organizational_context"]
        else:
            entry.update(group=record["group"], coverage_role=record["coverage"]["role"],
                         cohort=cohort(record), founded_year=record["founded"]["year"],
                         team_names=[p["name"] for p in record["people"]], stage=record["stage"],
                         previous_platforms=sorted({firm for person in record["people"] for firm in person.get("previous_firms", [])}),
                         prior_firm_case_count=sum(c["attribution"] == "prior_firm" for c in record["representative_cases"]),
                         current_firm_case_count=sum(c["attribution"] == "current_firm" for c in record["representative_cases"]))
        entries.append(entry)
    counts = {"organizations": len(records), "companies": len(records),
              "operating_organizations": len(companies), "investment_firms": len(investors),
              **{wave: waves[wave] for wave in WAVES}}
    statistics = {
        "operating_organizations": {
            "organizations": len(companies), "categories": len(categories),
            "source_records": sum(len(r["sources"]) for r in companies),
            "recruitment_links": sum(r["contacts"]["careers_url"] is not None for r in companies),
            "public_recruitment_emails": sum(r["contacts"]["recruitment_email"] is not None for r in companies)},
        "investment_firms": {
            "organizations": len(investors), "source_records": sum(len(r["sources"]) for r in investors),
            **{key: sum(cohort(r) == key for r in investors) for key, _ in GROUPS},
            "coverage_roles": {key: sum(r["coverage"]["role"] == key for r in investors) for key in ROLES}}}
    return {"schema_version": 4, "latest_checked_at": max((r["checked_at"] for _, r in records), default=None),
            "latest_operating_check": max((r["checked_at"] for r in companies), default=None),
            "latest_investment_firm_check": max((r["checked_at"] for r in investors), default=None),
            "counts": counts, "statistics": statistics, "organizations": entries}


def render(root):
    from organizations import select
    records = select(root)
    counts = Counter(r["targeting"]["wave"] for _, r in records)
    out = {"data/index.json": json.dumps(build_index(root, records), ensure_ascii=False, indent=2) + "\n"}
    banner = "<!-- Generated by tools/build.py from canonical JSON. Do not edit by hand. -->\n\n"
    first = [(folder,r) for folder,r in records if r["targeting"]["wave"] == "first"]
    operating = [(f,r) for f,r in first if r["organization_type"] == "operating_organization"]
    investing = [(f,r) for f,r in first if r["organization_type"] == "investment_firm"]
    page = banner + "# 第一波：新进 AI 机构\n\n[项目首页](../../README.md) · [机器目标索引](../index.json) · [完整资料目录](README.md)\n\n"
    page += "[大厂项目与拆分机构](corporate-ventures.md) · [母平台排查清单](incumbents.md)。有明确目标的内部团队、实验室或项目也可单列；按组织形态和母平台关系区分，不一律视为独立公司。\n\n"
    page += f"当前圈选 **{len(first)} 个第一波候选**：{len(operating)} 个经营型机构、{len(investing)} 个投资机构；另有 {counts['watchlist']} 个观察候选。\n\n"
    page += "这是基于现有材料的编辑性寻源名单，不是全市场清单、机构质量排名、成立年份证明或招聘承诺。不设统一成立年份门槛；上市也不单独决定新进／已有。标签整理日期与实际核查日期分开记录。\n\n本名单用于圈定机构；公开渠道与人物资料按任务逐项核查，个人 pitch 另按本人明确授权开展。\n\n"
    page += "## 经营型机构\n\n融资状态只反映现有披露的核验程度；不统一写成VC-backed，创始人支持、自筹、众筹、产业资本和融资口径冲突保留在机构档案原文中。\n\n| 机构 | 赛道 | 融资披露状态 | 原资料核查日 |\n| --- | --- | --- | --- |\n"
    for _,r in sorted(operating,key=lambda item:(item[1]['category_id'],item[1]['id'])):
        page += f"| [{md(r['name'])}](companies/{r['id']}.md) | {r['category_id']} | {FUNDING[r['investment']['verification_status']]} | {r['checked_at']} |\n"
    page += "\n## 新进投资机构\n\n[新 VC 识别 SOP](../../skills/find-startups/references/new-vc-spinouts.md) · [新机构与原平台对照](new-vc-spinouts.md)。新GP缺少成熟退出不自动排除；原平台案例不算新机构业绩。\n\n| 机构 | 原平台／团队背景 | 圈选依据 |\n| --- | --- | --- |\n"
    for _,r in investing:
        platforms='；'.join(p['name']+'：'+('、'.join(p.get('previous_firms', [])) or '原平台未列') for p in r['people'])
        page += f"| [{md(r['name'])}](companies/{r['id']}.md) | {md(platforms)} | {md(r['targeting']['rationale'])} |\n"
    page += "\n## 观察候选\n\n身份、边界或独立运作证据有缺口，先保留，不包装成已确认的第一波。\n\n| 机构 | 类型 | 待核实边界 |\n| --- | --- | --- |\n"
    for folder,r in records:
        if r['targeting']['wave']=='watchlist':page+=f"| [{md(r['name'])}]({folder}/{r['id']}.md) | {TYPES[r['organization_type']]} | {md(r['targeting']['rationale'])} |\n"
    page += "\n## 已有玩家\n\n原有资料保留在[后续名单](later.md)。成熟平台整体及常规业务团队留待后续；具名的新孵化项目、实验室和拆分机构按具体单元单独判断。\n"
    out['data/views/first-wave.md']=page
    later=banner+'# 已有玩家：后续研究登记\n\n[第一波入口](first-wave.md) · [机器索引](../index.json)\n\n已有玩家与新进第一波分开登记；研究方法见 [find-incumbents](../../skills/find-incumbents/SKILL.md)。底表和机构整体业务不等于已完成具体团队研究，不能据此推断岗位。\n\n| 机构 | 类型 | 本轮处理 |\n| --- | --- | --- |\n'
    for folder,r in records:
        if r['targeting']['wave']=='later':later+=f"| [{md(r['name'])}]({folder}/{r['id']}.md) | {TYPES[r['organization_type']]} | {md(r['targeting']['rationale'])} |\n"
    out['data/views/later.md']=later
    spin=banner+'# 新进投资机构与原平台\n\n[第一波入口](first-wave.md) · [识别与核验 SOP](../../skills/find-startups/references/new-vc-spinouts.md)\n\n独立创业不自动意味着法律分拆、资产转移或原基金持仓承接。下列关系取自已有团队及来源记录；不因资料整理提升核验状态。\n\n| 机构 | 寻源状态 | 团队／原平台 | 机构成立口径 |\n| --- | --- | --- | --- |\n'
    for _,r in records:
        if r['organization_type']=='investment_firm' and r['targeting']['player_group']=='new_entrant':
            team='；'.join(p['name']+'：'+('、'.join(p.get('previous_firms', [])) or '未列原平台') for p in r['people'])
            spin+=f"| [{md(r['name'])}](companies/{r['id']}.md) | {WAVES[r['targeting']['wave']]} | {md(team)} | {md(r['founded']['basis'])} |\n"
    out['data/views/new-vc-spinouts.md']=spin
    stream=io.StringIO(newline='');writer=csv.writer(stream,lineterminator='\n')
    writer.writerow(['entity_type','entity_id','name','channel_id','layer','platform','url','purpose','owner_scope','owner_name','checked_at','verification_status','source_ids'])
    for _,r in records:
        for c in r['channels']:writer.writerow([r['organization_type'],r['id'],r['name'],c['id'],c['layer'],c['platform'],c['url'],c['purpose'],c['owner']['scope'],c['owner']['name'],c['checked_at'],c['verification_status'],';'.join(c['source_ids'])])
    out['data/views/exports/channels.csv']=stream.getvalue()
    return out


def target_markdown(record):
    t=record['targeting']
    return '**目标标记：** '+WAVES[t['wave']]+' · '+t['player_group']+'（编辑归类，'+t['labelled_at']+'）\n\n'+t['rationale']+'\n\n标记依据：'+', '.join(t['source_ids'])+'。标记日期不更新业务事实核查日。\n\n'
