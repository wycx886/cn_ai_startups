"""Deterministically render Markdown, machine index and CSV from canonical JSON."""
import argparse,csv,io,json
from investors import build_outputs
from targets import render as target_outputs, target_markdown
from record_checks import channel_markdown
from corporate import context_markdown, render as corporate_outputs
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
STATUS={'confirmed_disclosure':'已核验披露（非完整现股东表）','partial':'部分核验','not_found':'未找到可靠公开披露','not_applicable':'内部单元，不适用独立主体股权融资'}
def read_data():
 taxonomy=json.loads((ROOT/'data/taxonomy.json').read_text())
 companies=[json.loads(p.read_text()) for p in sorted((ROOT/'data/companies').glob('*.json'))]
 companies.sort(key=lambda c:(c['category_id'],c['id']))
 return taxonomy,companies
def md(value):
 if value is None:return '未查到公开信息'
 return str(value).replace('|','\\|').replace('\r','').replace('\n','<br>')
def csv_text(rows):
 out=io.StringIO(newline='');writer=csv.writer(out,lineterminator='\n');writer.writerows(rows);return out.getvalue()
def dumps(data):return json.dumps(data,ensure_ascii=False,indent=2)+'\n'
def outputs():
 tax,companies=read_data();categories={c['id']:c for c in tax['categories']}
 out={};latest=max(c['checked_at'] for c in companies)
 counts={'companies':len(companies),'categories':len(categories),'source_records':sum(len(c['sources']) for c in companies),'recruitment_links':sum(c['contacts']['careers_url'] is not None for c in companies),'public_recruitment_emails':sum(c['contacts']['recruitment_email'] is not None for c in companies)}
 banner='<!-- Generated by tools/build.py from canonical JSON. Do not edit by hand. -->\n\n'
 readme=banner+'# AI 机构与机会资料目录\n\n[项目首页](../../README.md) · [Agent 规则](../../AGENTS.md)\n\n'
 readme+='[第一波新进机构](first-wave.md) · [新进VC与原平台](new-vc-spinouts.md) · [已有玩家后续登记](later.md)\n\n'
 readme+='[大厂项目、实验室与拆分机构](corporate-ventures.md) · [国内母平台排查清单](platforms.md)\n\n'
 readme+='JSON 是公开事实的唯一维护源；本目录、公司档案、机构档案和 CSV 自动生成。公司按业务分类，不预设个人求职匹配或优先级。\n\n'
 readme+='目前收录 **%s 个经营型机构／项目、%s 个主赛道、%s 条来源记录**；记录 %s 个招聘入口、%s 个公开招聘邮箱。最近业务资料核查日期：%s；资料是研究快照，不保证职位仍开放。\n\n'%tuple([counts[k] for k in ['companies','categories','source_records','recruitment_links','public_recruitment_emails']]+[latest])
 readme+='## 阅读入口\n\n| 需求 | 入口 |\n| --- | --- |\n| 公司机器索引 | [data/index.json](../index.json) |\n| 分类与方法 | [taxonomy.md](taxonomy.md) |\n| 公司原始 JSON | [data/companies/](../companies/) |\n| 公司筛选表 | [companies.csv](exports/companies.csv) |\n| 公司来源表 | [sources.csv](exports/sources.csv) |\n| 字段说明 | [数据模型](../README.md) |\n\n'
 readme+='## 按赛道找公司\n\n'
 for category in tax['categories']:
  group=[c for c in companies if c['category_id']==category['id']]
  readme+='### '+category['id']+' '+category['name']+' · '+str(len(group))+' 家\n\n'
  readme+=' · '.join('['+c['name']+'](companies/'+c['id']+'.md)' for c in group)+'\n\n'
 readme+='## 资料口径\n\n投资背景仅为有出处的历史披露；不表示完整现股东名册。同类区别属于编辑分析，缺失值不表示确定不存在。招聘、校园／历史投递和其他联系邮箱的用途以逐条备注为准。\n\n更新只改公共 JSON，再运行 `tools/build.py`；个人信息和投递进展写在配置的私人工作区，见 [工作流](../../skills/setup-workspace/references/workflow.md)。\n'
 out['data/views/README.md']=readme
 taxonomy=banner+'# 分类框架\n\n'+tax['method']+'\n\n版本：'+tax['version']+'。\n\n'
 taxonomy+='## 主赛道\n\n| ID | 名称 | 分类边界 | 细分方向 |\n| --- | --- | --- | --- |\n'
 for c in tax['categories']:taxonomy+='| '+' | '.join(map(md,[c['id'],c['name'],c['boundary'],'；'.join(c['subtracks'])]))+' |\n'
 taxonomy+='\n## 参考框架\n\n'
 for r in tax['references']:
  taxonomy+='### '+r['organization']+'\n\n['+r['title']+']('+r['url']+') · '+r['date']+'\n\n原始方法：'+r['finding']+'\n\n本库采用：'+r['adopted']+'\n\n'
 taxonomy+='## 口径与限制\n\n'+'\n'.join('- '+x for x in tax['caveats'])+'\n'
 out['data/views/taxonomy.md']=taxonomy
 rows=[['id','name','category_id','category','focus','products','comparison','peers','investment','investment_status','locations','website','careers_url','recruitment_email','other_email','other_email_purpose','notes','checked_at','sources']]
 sources=[['company_id','company','source_id','title','url','supports','published_date','checked_at']]
 for c in companies:
  contact=c['contacts'];category=categories[c['category_id']]['name']
  page=banner+'# '+c['name']+'\n\n[返回索引](../README.md) · [原始 JSON](../../companies/'+c['id']+'.json)\n\n'
  page+='机构／项目 ID：`'+c['id']+'` · 主赛道：'+c['category_id']+' '+category+' · 核查日期：'+c['checked_at']+'\n\n'
  page+=target_markdown(c)
  page+=context_markdown(c)
  page+='别名与原表名称：'+'；'.join(c['aliases'])+'\n\n'
  page+='## 业务与产品\n\n**细分方向：** '+c['focus']+'\n\n'+c['products']+'\n\n**城市记录：** '+(c['locations_text'] or '未查到公开记录')+'\n\n'
  page+='## 同类区别\n\n'+c['comparison']['summary']+'\n\n比较对象：'+'、'.join(c['comparison']['peer_names'])+'。以上为产品定位分析，非性能排名。\n\n'
  page+='## 投资背景\n\n'+c['investment']['summary']+'\n\n**披露状态：** '+STATUS[c['investment']['verification_status']]+'。\n\n'
  page+='## 公开渠道\n\n| 类型 | 记录 |\n| --- | --- |\n'
  for label,key in [('官网','website'),('招聘入口','careers_url'),('招聘投递邮箱','recruitment_email'),('其他公开邮箱','other_email'),('其他邮箱用途','other_email_purpose')]:
   value=contact[key];value=('['+md(value)+']('+value+')') if value and key in ('website','careers_url') else md(value)
   page+='| '+label+' | '+value+' |\n'
  page+='\n招聘入口可能是官网、平台公司页或历史岗位帖，适用范围见备注；有入口不保证当前在招。其他联系邮箱不自动视为投递邮箱。\n\n'
  page+=channel_markdown(c)
  if c['notes']:page+='## 核查备注\n\n'+c['notes']+'\n\n'
  page+='## 证据与来源\n\n| 来源 ID | 页面 | 支持内容 | 公开日期 | 核查日期 |\n| --- | --- | --- | --- | --- |\n'
  for s in c['sources']:
   page+='| '+s['id']+' | ['+md(s['title'])+']('+s['url']+') | '+md(s['supports'])+' | '+(s['published_date'] or '未标明')+' | '+s['checked_at']+' |\n'
   sources.append([c['id'],c['name'],s['id'],s['title'],s['url'],s['supports'],s['published_date'],s['checked_at']])
  out['data/views/companies/'+c['id']+'.md']=page
  rows.append([c['id'],c['name'],c['category_id'],category,c['focus'],c['products'],c['comparison']['summary'],'；'.join(c['comparison']['peer_names']),c['investment']['summary'],c['investment']['verification_status'],c['locations_text'],contact['website'],contact['careers_url'],contact['recruitment_email'],contact['other_email'],contact['other_email_purpose'],c['notes'],c['checked_at'],'\n'.join(s['url'] for s in c['sources'])])
 out['data/views/exports/companies.csv']=csv_text(rows);out['data/views/exports/sources.csv']=csv_text(sources)
 investor_files,investor_intro=build_outputs(ROOT)
 out.update(investor_files)
 if investor_intro:
  out['data/views/README.md']=out['data/views/README.md'].replace('## 阅读入口',investor_intro+'## 阅读入口',1)
 out.update(target_outputs(ROOT))
 out.update(corporate_outputs(ROOT))
 return out

def main():
 parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
 expected=outputs();mismatches=[]
 for name,content in expected.items():
  path=ROOT/name
  if args.check:
   if not path.exists() or path.read_bytes()!=content.encode('utf-8'):mismatches.append(name)
  else:path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(content.encode('utf-8'))
 stale={p.relative_to(ROOT).as_posix() for p in (ROOT/'data/views').rglob('*') if p.is_file() and p.suffix in {'.md','.csv'}}-set(expected)
 if stale:mismatches.extend(sorted(stale))
 if mismatches:raise SystemExit('Generated content differs; regenerate or review stale files: '+', '.join(mismatches))
 print(('Checked' if args.check else 'Generated')+' '+str(len(expected))+' derived files.')
if __name__=='__main__':main()
