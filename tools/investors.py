"""Generate investor profiles and indexes; facts remain in data/companies/*.json."""
import csv,io,json
from targets import target_markdown
from record_checks import channel_markdown
ROLES={'main':'主要样本','watchlist':'观察补充','adjacent':'相关机构'}
GROUPS=[('recent','2024–2026 新设机构'),('new_generation','2020–2023 成立的新一代机构'),('established','成熟机构'),('founding_unconfirmed','成立时间待确认')]
def cohort(c):
 if c['group']=='established':return 'established'
 year=c['founded']['year']
 if year is None:return 'founding_unconfirmed'
 return 'recent' if year>=2024 else 'new_generation'
def md(value):return '未查到公开信息' if value is None else str(value).replace('|','\\|').replace('\n','<br>')
def csv_text(rows):
 out=io.StringIO(newline='');writer=csv.writer(out,lineterminator='\n');writer.writerows(rows);return out.getvalue()
def build_outputs(root):
 records=[c for p in sorted((root/'data/companies').glob('*.json')) for c in [json.loads(p.read_text())] if c['organization_type']=='investment_firm']
 list_data=json.loads((root/'data/lists/vcs.json').read_text())
 memberships={e['company_id']:e for e in list_data['entries']}
 order={key:i for i,(key,_) in enumerate(GROUPS)};records.sort(key=lambda c:(order[cohort(c)],c['id']))
 banner='<!-- Generated by tools/build.py from canonical JSON. Do not edit by hand. -->\n\n'
 stats={key:sum(cohort(c)==key for c in records if c['id'] in memberships) for key,_ in GROUPS}
 role_counts={key:sum(c['coverage']['role']==key for c in records if c['id'] in memberships) for key in ROLES}
 latest_checked_at=max((c['checked_at'] for c in records if c['id'] in memberships), default='未收录参考入口')
 out={}
 overview=banner+'# 中国 VC 机构研究\n\n[资料目录](README.md) · [仓库首页](../../README.md) · [机器名单](../lists/vcs.json) · [机器索引](../index.json) · [筛选与归因方法](../../skills/find-startups/references/investment-cases.md)\n\n'
 overview+=list_data['scope_note']+'\n\n'
 overview+='按成立时间与机构属性整理，不是基金收益排名。新机构创始人在原平台的案例与新机构自己的案例分别记录；机构注册、管理人登记、首期基金成立也分别说明。\n\n'
 overview+='本期 '+str(len(memberships))+' 个参考入口，最近档案核查日期 '+latest_checked_at+'；'+str(stats['recent'])+' 家列入 2024–2026 新设组，'+str(stats['new_generation'])+' 家列入 2020–2023 新一代组，'+str(stats['established'])+' 家成熟机构。\n\n'
 overview+='主要样本 '+str(role_counts['main'])+' 家；观察补充 '+str(role_counts['watchlist'])+' 家；相关机构 '+str(role_counts['adjacent'])+' 家。这是证据覆盖和研究范围区分，不是收益或质量评分。\n\n'
 rows=[['id','name','cohort','coverage_role','founded_year','team','focus','stage','why_follow_editorial','difference_editorial','recent_activity','prior_firm_cases','current_firm_cases','website','careers_url','recruitment_email','other_email','other_email_purpose','notes','checked_at']]
 source_rows=[['investor_id','institution','source_id','title','url','supports','published_date','checked_at']]
 for key,title in GROUPS:
  group=[c for c in records if cohort(c)==key and c['id'] in memberships]
  if not group:continue
  overview+='## '+title+' · '+str(len(group))+' 家\n\n| 机构 | 研究位置 | 成立口径 | 团队来历 | 方向 | 案例归因 |\n| --- | --- | --- | --- | --- | --- |\n'
  for c in group:
   team='；'.join(p['name']+'（'+('、'.join(p.get('previous_firms', [])) if p.get('previous_firms', []) else (p['role'] or '未列原平台'))+'）' for p in c['people'])
   old=sum(x['attribution']=='prior_firm' for x in c['representative_cases']);new=len(c['representative_cases'])-old
   overview+='| ['+md(c['name'])+'](companies/'+c['id']+'.md) | '+ROLES[c['coverage']['role']]+' | '+md(c['founded']['year'])+'；'+md(c['founded']['basis'])+' | '+md(team)+' | '+md(c['focus'])+' | 原平台 '+str(old)+' 条；本机构 '+str(new)+' 条 |\n'
  overview+='\n'
 for c in records:
  page=banner+'# '+c['name']+'\n\n[资料目录](../README.md) · [VC 参考名单](../vcs.md) · [原始 JSON](../../companies/'+c['id']+'.json)\n\n'
  page+='机构 ID：`'+c['id']+'` · 核查日期：'+c['checked_at']+'\n\n'
  page+=target_markdown(c)
  page+='## 成立与资料范围\n\n成立年份：'+md(c['founded']['year'])+'。口径：'+c['founded']['basis']+'\n\n'
  page+=ROLES[c['coverage']['role']]+' -- '+c['coverage']['reason']+'\n\n'
  page+='\n## 投资方向与阶段\n\n'+md(c['focus'])+'\n\n阶段：'+md(c['stage'])+'\n\n'
  page+='## 案例与成绩归因\n\n'
  for attr,title in [('prior_firm','创始人或团队在原平台的案例'),('current_firm','本机构的案例')]:
   cases=[x for x in c['representative_cases'] if x['attribution']==attr]
   page+='### '+title+'\n\n'
   if not cases:page+='本轮未收录足够证据支持的案例；不表示确定没有投资。\n\n';continue
   for case in cases:
    refs='、'.join(case['evidence_source_ids'])
    page+='- **'+case['company']+'** · 归因：'+case['investor_or_team']+'。'+case['outcome']+'（来源 '+refs+'）\n'
   page+='\n'
  page+='IPO、账面估值增长、知名公司投资和实际已实现回报不是同一口径；未公开的 DPI/IRR 不补造。\n\n'
  page+='## 近期活动\n\n'+c['recent_activity']+'\n\n## 值得跟踪的理由与同类区别（编辑分析）\n\n'+c['why_follow']+'\n\n'+c['difference']+'\n\n'
  page+='## 公开渠道\n\n| 类型 | 记录 |\n| --- | --- |\n'
  for label,field in [('官网','website'),('招聘入口','careers_url'),('公开招聘邮箱','recruitment_email'),('其他邮箱','other_email'),('其他邮箱用途','other_email_purpose')]:
   value=c['contacts'][field];value='['+md(value)+']('+value+')' if value and field in ('website','careers_url') else md(value)
   page+='| '+label+' | '+value+' |\n'
  page+=channel_markdown(c)
  if c['notes']:page+='\n## 核查备注\n\n'+c['notes']+'\n'
  page+='\n## 证据与来源\n\n| ID | 来源 | 支持内容 | 公开日期 | 核查日期 |\n| --- | --- | --- | --- | --- |\n'
  for s in c['sources']:
   page+='| '+s['id']+' | ['+md(s['title'])+']('+s['url']+') | '+md(s['supports'])+' | '+(s['published_date'] or '未标明')+' | '+s['checked_at']+' |\n'
   source_rows.append([c['id'],c['name'],s['id'],s['title'],s['url'],s['supports'],s['published_date'],s['checked_at']])
  out['data/views/companies/'+c['id']+'.md']=page
  def case_summary(attr):return '；'.join(x['company']+'：'+x['investor_or_team']+'；'+x['outcome'] for x in c['representative_cases'] if x['attribution']==attr)
  rows.append([c['id'],c['name'],cohort(c),c['coverage']['role'],c['founded']['year'],'；'.join(x['name'] for x in c['people']),c['focus'],c['stage'],c['why_follow'],c['difference'],c['recent_activity'],case_summary('prior_firm'),case_summary('current_firm'),*[c['contacts'][k] for k in ['website','careers_url','recruitment_email','other_email','other_email_purpose']],c['notes'],c['checked_at']])
 out['data/views/vcs.md']=overview.rstrip()+'\n'
 out['data/views/exports/investors.csv']=csv_text(rows);out['data/views/exports/investor-sources.csv']=csv_text(source_rows)
 intro='## VC 机构研究\n\n已建档 **'+str(len(records))+' 家机构**，区分 2024–2026 新设机构、2020–2023 新一代机构与成熟 VC。创始人原平台成绩和新机构投资分别标注。\n\n[查看 VC 参考名单与档案](vcs.md) · [投资机构筛选表](exports/investors.csv) · [投资机构来源表](exports/investor-sources.csv) · [Agent 机器索引](../index.json) · [筛选方法](../../skills/find-startups/references/investment-cases.md)\n\n'
 return out,intro
